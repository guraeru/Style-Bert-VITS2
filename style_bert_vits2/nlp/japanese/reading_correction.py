# ============================================================================
# モーラ数計算
# ============================================================================

_MORA_PATTERN = re.compile(
    "|".join(
        map(
            re.escape,
            sorted(MORA_KATA_TO_MORA_PHONEMES.keys(), key=len, reverse=True),
        )
    )
)


def _is_kanji(char: str) -> bool:
    """文字が CJK 漢字かどうかを判定する。"""
    cp = ord(char)
    return (0x4E00 <= cp <= 0x9FFF) or (0x3400 <= cp <= 0x4DBF) or cp == 0x3005


def _is_noun_ending(char: str) -> bool:
    """
    文字が名詞系語尾として「値」の接尾辞 ～値（チ）を誘発する文字かを判定する。

    対象:
    - CJK 漢字 (設定値, 最大値 etc.)
    - 全角・半角カタカナ (ラフネス値, メタリック値, デフォルト値 etc.)
    - ASCII ラテン文字 (IOR値 etc.)
    - ASCII 数字は対象外（「1値」のような表現は現れない）

    ひらがなで終わる形態素（の/を/は 等の助詞、い/な形容詞語尾）は
    対象外とすることで、「この値」「大きい値」→ アタイ を正しく維持する。
    """
    cp = ord(char)
    # CJK 漢字
    if (0x4E00 <= cp <= 0x9FFF) or (0x3400 <= cp <= 0x4DBF) or cp == 0x3005:
        return True
    # 全角カタカナ（ァ-ン, ヴ, ヵ, ヶ）
    if 0x30A0 <= cp <= 0x30FF:
        return True
    # 半角カタカナ (ｦ-ﾝ)
    if 0xFF66 <= cp <= 0xFF9D:
        return True
    # ASCII ラテン文字 (a-z, A-Z)
    if (0x41 <= cp <= 0x5A) or (0x61 <= cp <= 0x7A):
        return True
    # 全角ラテン文字 (Ａ-Ｚ: U+FF21-FF3A, ａ-ｚ: U+FF41-FF5A)
    # pyopenjtalk は日本語文中のアルファベットを全角に変換して返すことがある
    if (0xFF21 <= cp <= 0xFF3A) or (0xFF41 <= cp <= 0xFF5A):
        return True
    return False


def _count_morae(katakana: str) -> int:
    """カタカナ読みからモーラ数を計算する。"""
    clean = katakana.replace("'", "").replace("\u2019", "")
    morae = len(_MORA_PATTERN.findall(clean))
    long_vowels = clean.count("ー")
    return morae + long_vowels


