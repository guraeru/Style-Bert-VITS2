# ============================================================================
# 文脈依存の補正ルール
# ============================================================================
# 前後の形態素情報を参照して読みを補正するルール。
#
# 形式: (prev_endswith, surface, next_startswith, correct_pron)
#   prev_endswith: 前の形態素の string 末尾（None = 条件なし）
#   surface: 対象形態素の string（完全一致）
#   next_startswith: 次の形態素の string 先頭（None = 条件なし）
#   correct_pron: 正しい読み
#
# ルールは上から順に評価され、最初にマッチしたものが適用される。

CONTEXT_RULES: list[tuple[str | None, str, str | None, str]] = [
    # ------------------------------------------------------------------
    # 「行っ」の読み分け
    #   を行っ（た/て）→ オコナッ（行う: carry out）
    #   に/へ行っ（た/て）→ イッ（行く: go）
    # ------------------------------------------------------------------
    ("を", "行っ", None, "オコナッ"),
    # 「に行っ」「へ行っ」は pyopenjtalk のデフォルト「イッ」が正しいのでルール不要

    # ------------------------------------------------------------------
    # 「方」の読み分け
    #   〜の方（ほう）→ 方向・比較 (pyopenjtalk デフォルト)
    #   方が/方は/方に/方も/方の → 人を指す場合は「カタ」
    #   ※ 「〜する方が」は「ほうが」が正しいため、汎用ルールにはしない
    #   ※ ここでは「この方」「あの方」等の敬称用法のみ対応
    # ------------------------------------------------------------------
    ("の", "方", "が", "カタ"),
    ("の", "方", "は", "カタ"),
    ("の", "方", "に", "カタ"),
    ("の", "方", "も", "カタ"),
    ("の", "方", "を", "カタ"),
    ("る", "方", "が", "カタ"),  # 〜される方が
    ("る", "方", "は", "カタ"),
    ("る", "方", "に", "カタ"),

    # ------------------------------------------------------------------
    # 「人」が人数を表す場合の読み修正
    # ------------------------------------------------------------------
    ("一", "人", None, "リ"),   # 一人 → ヒトリ (OpenJTalk分割時: 一+人)
    ("二", "人", None, "リ"),   # 二人 → フタリ (OpenJTalk分割時: 二+人)

    # ------------------------------------------------------------------
    # 「生」の読み分け
    #   生 + まれ/まれる → うまれ（生まれる）
    # ------------------------------------------------------------------
    (None, "生", "まれ", "ウ"),

    # ------------------------------------------------------------------
    # 「日」の読み分け補助
    #   一 + 日 → ニチ（一日分 etc の場合）
    #   ※ 「一日」が一形態素なら SURFACE_CORRECTIONS で処理
    #   ※ OpenJTalk が「一」+「日」に分割した場合のフォールバック
    # ------------------------------------------------------------------
    ("一", "日", None, "ニチ"),
]


# ============================================================================
# 読みバリデーション
# ============================================================================

_KATAKANA_VALID_PATTERN = re.compile(r"^[ァ-ヶー\u0027\u2019]+$")


def _is_valid_katakana_reading(pron: str) -> bool:
    """読みが有効なカタカナ文字列かチェックする（無声化マーク U+0027/' や U+2019/' を含む）。"""
    if not pron:
        return False
    return bool(_KATAKANA_VALID_PATTERN.match(pron))


# ============================================================================
# メイン補正関数
# ============================================================================


def correct_njd_features(
    features: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """
    pyopenjtalk.run_frontend() の出力に対して読み補正を適用する。

    この関数は run_frontend() と make_label()/text_to_sep_kata() の間に挿入して使用する。

    Args:
        features: run_frontend() の戻り値（NJD 特徴量のリスト）

    Returns:
        補正済みの NJD 特徴量リスト（入力リストを直接変更する）
    """
    if not features:
        return features

    n = len(features)

    for i, feat in enumerate(features):
        surface = feat.get("string", "")
        original_pron = feat.get("pron", "")

        if not surface or not original_pron:
            continue

        corrected_pron: str | None = None

        # 1. 文脈依存ルールをチェック（優先度高）
        prev_surface = features[i - 1].get("string", "") if i > 0 else ""
        next_surface = features[i + 1].get("string", "") if i < n - 1 else ""

        # 1a. 「値」特殊処理: 漢字複合語の後の「値」は接尾辞 ～値（チ）
        #     例: 最大+値→サイダイチ, 絶対+値→ゼッタイチ, 設定+値→セッテイチ
        #     それ以外の場合は SURFACE_CORRECTIONS のデフォルト アタイ が適用される
        if surface == "値" and prev_surface and _is_noun_ending(prev_surface[-1]):
            corrected_pron = "チ"

        if corrected_pron is None:
            for prev_end, rule_surface, next_start, rule_pron in CONTEXT_RULES:
                if rule_surface != surface:
                    continue
                if prev_end is not None and not prev_surface.endswith(prev_end):
                    continue
                if next_start is not None and not next_surface.startswith(next_start):
                    continue
                corrected_pron = rule_pron
                break

        # 2. 表層形ベース補正をチェック（文脈ルールでマッチしなかった場合）
        if corrected_pron is None and surface in SURFACE_CORRECTIONS:
            corrected_pron = SURFACE_CORRECTIONS[surface]

        # 3. 補正を適用
        if corrected_pron is not None:
            # 無声化マークを除去して比較（U+0027 ' と U+2019 ' の両方に対応）
            clean_original = original_pron.replace("'", "").replace("\u2019", "")
            if clean_original != corrected_pron:
                logger.debug(
                    f"読み補正: {surface} [{clean_original}] → [{corrected_pron}]"
                )
                feat["pron"] = corrected_pron
                # mora_size も更新（make_label で使われる）
                new_mora = _count_morae(corrected_pron)
                if "mora_size" in feat:
                    feat["mora_size"] = new_mora

        # 4. 読みバリデーション
        final_pron = feat.get("pron", "")
        # pyopenjtalk は句読点を「、」「？」等の全角カタカナ外文字で返す
        # これらはバリデーション対象外とする
        if (
            final_pron
            and final_pron not in ("、", "？", "！")
            and not _is_valid_katakana_reading(final_pron)
        ):
            logger.warning(
                f"不正な読み検出: {surface} → [{final_pron}] "
                f"(有効なカタカナではありません)"
            )

    return features
