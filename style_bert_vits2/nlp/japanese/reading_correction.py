"""
漢字読み補正モジュール

pyopenjtalk (OpenJTalk + MeCab + NAIST jdic) の形態素解析結果に対して、
既知の読み間違いを後処理で補正する。

## 設計方針

pyopenjtalk は高品質な形態素解析器だが、以下のケースで読み間違いが発生しやすい：

1. 多読語（同じ漢字で複数の読みがある語）の文脈判別ミス
   例: 行（い/おこな/こう）、何（なに/なん）、生（なま/せい/い）
2. 辞書に未登録の複合語・専門用語
3. 形態素解析の分割ミスによる読み違い

本モジュールでは、run_frontend() の出力（NJD 特徴量リスト）に対して
後処理として読み補正を適用し、make_label() や text_to_sep_kata() に渡す。

## 補正ルール

補正は以下の順序で適用される：
1. 連結パターン補正: 前後の形態素をまたぐパターンを検出し補正
2. 表層形ベース補正: 表層形のみで一意に読みが確定する語を補正
3. 読みバリデーション: 補正後の読みが妥当かチェックし警告

## 拡張方法

新しい補正を追加するには：
- 文脈不要の場合: SURFACE_CORRECTIONS に「表層形: カタカナ読み」を追加
- 文脈必要の場合: CONTEXT_RULES にタプルを追加（フォーマットは下記参照）
"""

import re
